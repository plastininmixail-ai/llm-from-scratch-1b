def main():
    import json
    from collections import Counter
    counter = Counter(label for _, label in TRAINING_DATA)
    print(f"Всего примеров: {len(TRAINING_DATA)}")
    for intent, count in counter.most_common():
        print(f"  {intent}: {count}")

    # Сохраняем
    DATA_PATH.parent.mkdir(parents=True, exist_ok=True)
    with DATA_PATH.open("w", encoding="utf-8") as f:
        json.dump({"examples": TRAINING_DATA, "counts": dict(counter)}, f, ensure_ascii=False, indent=2)
    print(f"\n📤 {DATA_PATH}")


if __name__ == "__main__":
    main()
